import { readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const failures = [];
const checks = [];

function check(label, condition, detail = "") {
  checks.push({ label, condition });
  if (!condition) failures.push(`${label}${detail ? `: ${detail}` : ""}`);
}

function read(path) {
  try {
    return readFileSync(resolve(root, path), "utf8");
  } catch {
    failures.push(`Required file missing or unreadable: ${path}`);
    return "";
  }
}

const workflow = read(".github/workflows/deploy-cloudflare.yml");
const manifestText = read("manifest.webmanifest");
let manifest = null;
try {
  manifest = JSON.parse(manifestText);
  check("PWA manifest is valid JSON", true);
} catch (error) {
  check("PWA manifest is valid JSON", false, error.message);
}

const requiredSourceFiles = [
  "index.html", "favorites.html", "styles.css", "app.js", "supabase-client.js",
  "seller.html", "seller.css", "seller.js", "merchant-profile.html",
  "merchant-profile.js", "customer-profile.html", "customer-profile.js",
  "market.html", "market.css", "market.js", "store.html", "platform.html",
  "platform.css", "platform.js", "platform/index.html", "manifest.webmanifest",
  "pwa-register.js", "navigation-back.js", "sw.js", "offline.html", "icons/bben.svg",
  "icons/bben-192.svg", "icons/bben-512.svg"
];

for (const file of requiredSourceFiles) {
  check(`Deployment source exists: ${file}`, existsSync(resolve(root, file)));
}

check("Deploy workflow checks out repository", workflow.includes("actions/checkout@"));
check("Deploy workflow prepares public assets", workflow.includes("mkdir -p public"));
check("Deploy workflow configures Cloudflare deployment", /wrangler|cloudflare/i.test(workflow));

if (manifest) {
  check("Manifest defines root scope", manifest.scope === "/");
  check("Manifest has a start_url", typeof manifest.start_url === "string" && manifest.start_url.startsWith("/"));
  check("Manifest display mode supports app-like display", ["standalone", "fullscreen", "minimal-ui"].includes(manifest.display));
  check("Manifest defines at least two icons", Array.isArray(manifest.icons) && manifest.icons.length >= 2);
  for (const expectedSize of ["192x192", "512x512"]) {
    const icon = manifest.icons?.find((item) => item.sizes === expectedSize);
    check(`Manifest declares ${expectedSize} PNG icon`, Boolean(icon && icon.type === "image/png" && icon.src));
    if (icon) {
      check(`PNG icon is generated by deploy workflow: ${icon.src}`, workflow.includes(icon.src.split("/").pop()));
    }
  }
}

const pwa = read("pwa-register.js");
check("PWA script registers service worker", pwa.includes("serviceWorker.register"));
check("PWA script listens for install prompt", pwa.includes("beforeinstallprompt"));

const serviceWorker = read("sw.js");
check("Service worker includes offline fallback", /offline\.html/.test(serviceWorker));

for (const result of checks) {
  process.stdout.write(`${result.condition ? "PASS" : "FAIL"} ${result.label}\n`);
}

if (failures.length) {
  process.stderr.write(`\nValidation failed: ${failures.length} issue(s)\n- ${failures.join("\n- ")}\n`);
  process.exitCode = 1;
} else {
  process.stdout.write(`\nValidation passed: ${checks.length} checks. This is a static source check, not a live browser/deployment test.\n`);
}
